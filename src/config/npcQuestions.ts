/**
 * NPC 问答配置
 *
 * 每个 NPC 向玩家提出一个问题，包含衔接语、角色提示语和四个选项。
 * 玩家选择正确 → 获得对应灵印；选择错误 → 失败次数 +1。
 * 同一 NPC 可反复对话，直到获得灵印或累计失败 3 次。
 */

export interface NPCQuestion {
  /** 衔接语：进入问答前的过渡台词 */
  transition: string
  /** 角色提示语：暗示玩家应如何回答 */
  hint: string
  /** 问题内容 */
  question: string
  /** 四个选项 */
  options: {
    A: string
    B: string
    C: string
    D: string
  }
  /** 正确答案 */
  correct: 'A' | 'B' | 'C' | 'D'
  /** 回答成功后的 NPC 回复 */
  successReply: string
  /** 个性化错误提示：[第1次, 第2次, 第3次(处决)] */
  errorReplies: [string, string, string]
}

