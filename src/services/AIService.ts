//
// 根据当前模式（模拟/真实）自动选择实现
// 真实 AI 模式失败时自动降级到模拟模式，保证游戏始终可运行
// ========================================================================

/**
 * 获取 AI 回复（异步）
 *
 * @param userInput      玩家输入的文字
 * @param npcContext      NPC 的完整上下文信息（名字、性格、背景、诉求）
 * @returns              NPC 的回复文字
 */
export async function getAIResponse(
  userInput: string,
  npcContext: NPCContext,
): Promise<string> {
  // ---- 模拟模式：直接从预设库返回 ----
  if (USE_MOCK) {
    return getMockResponse(userInput, npcContext.personality)
  }

  // ---- 真实 AI 模式：调用 DeepSeek API ----
  try {
    const reply = await callDeepSeekAPI(userInput, npcContext)
    return reply
  } catch (error) {
    // API 调用失败，自动降级到模拟模式
    console.warn('[AIService] API 调用失败，降级到模拟模式:', error)

    // 本次请求使用模拟回复返回
    return getMockResponse(userInput, npcContext.personality)
  }
}
